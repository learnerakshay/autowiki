import { expect, test, webkit } from '@playwright/test'
import { auditAxe } from './helpers/axe.js'

test.use({ reducedMotion: 'reduce' })
test('keyboard palette: combobox, result count, focus return, fuzzy navigation and zero API prefill', async ({ page }) => {
  let requests = 0
  await page.route('**/api/**', (route) => { requests++; return route.fulfill({ contentType: 'application/json', body: '{}' }) })
  await page.goto('/workspace')
  const trigger=page.getByRole('button',{name:'Open command palette'})
  await trigger.focus(); await page.keyboard.press('Control+k')
  const input=page.getByRole('combobox')
  await expect(input).toBeFocused()
  await expect(input).toHaveAttribute('aria-controls', /.+-list/)
  await expect(page.getByRole('listbox')).toBeVisible()
  expect(await auditAxe(page)).toEqual([])
  await page.keyboard.press('Escape'); await expect(trigger).toBeFocused()
  await page.keyboard.press('Control+k')
  await input.fill('https://github.com/acme/repo.git')
  await expect(page.getByRole('option')).toHaveCount(2)
  await page.keyboard.press('End'); await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/chat\?repo=acme%2Frepo$/)
  await expect(page.getByLabel('Repository',{exact:true})).toHaveValue('acme/repo')
  await expect(page.getByRole('heading',{level:1})).toBeFocused()
  await expect(page).toHaveTitle('Chat — AutoWiki')
  await page.keyboard.press('Control+k'); await input.fill('wrksp'); await page.keyboard.press('Home'); await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/workspace$/)
  await page.keyboard.press('Control+k'); await input.fill('acme/another'); await page.keyboard.press('Home'); await page.keyboard.press('Enter')
  await expect(page.getByLabel('GitHub repository',{exact:true})).toHaveValue('acme/another')
  expect(requests).toBe(0)
})
test('palette and nav stay still at 1440/390 and WebKit supports keyboard prefill', async ({ browser }) => {
  for(const width of [1440,390]) {
    const context=await browser.newContext({baseURL:process.env.BASE_URL,reducedMotion:'reduce',viewport:{width,height:844}})
    const page=await context.newPage(); await page.goto('/chat')
    await expect(page.getByRole('heading',{level:1})).toBeVisible()
    const left=await page.locator('.ln__bar').evaluate((el)=>el.getBoundingClientRect().left)
    await page.getByRole('button',{name:'Open command palette'}).click()
    await expect(page.getByRole('combobox')).toBeFocused()
    expect(await page.locator('.ln__bar').evaluate((el)=>el.getBoundingClientRect().left)).toBe(left)
    await page.keyboard.press('Escape'); await context.close()
  }
  const engine=await webkit.launch({ executablePath: webkit.executablePath() })
  const context=await engine.newContext({baseURL:process.env.BASE_URL,reducedMotion:'reduce'})
  const page=await context.newPage(); let requests=0
  await page.route('**/api/**',(route)=>{requests++;return route.abort()})
  await page.goto('/workspace'); await expect(page.getByRole('heading',{level:1})).toBeVisible()
  await page.keyboard.press('Control+k'); await page.getByRole('combobox').fill('acme/repo')
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter')
  await expect(page.getByLabel('Repository',{exact:true})).toHaveValue('acme/repo')
  expect(requests).toBe(0)
  expect(await auditAxe(page)).toEqual([])
  await context.close(); await engine.close()
})
test('route titles/focus, hash clearance and browser back restore scroll', async ({ page }) => {
  await page.goto('/architecture')
  await expect(page.getByRole('heading',{level:1})).toBeVisible()
  await page.getByRole('link',{name:'Explore the system'}).press('Enter')
  await expect(page.locator('#system-overview-title')).toBeFocused()
  expect(await page.locator('#system-overview-title').evaluate((el)=>el.getBoundingClientRect().top)).toBeGreaterThanOrEqual(70)
  await page.evaluate(()=>window.scrollTo(0,550))
  const before=await page.evaluate(()=>scrollY)
  await page.locator('.ln').getByRole('link',{name:'Chat',exact:true}).press('Enter')
  await expect(page.getByRole('heading',{level:1})).toBeFocused()
  await expect(page).toHaveTitle('Chat — AutoWiki')
  await page.goBack()
  await expect(page).toHaveURL(/architecture/)
  await expect.poll(()=>page.evaluate(()=>scrollY)).toBe(before)
  await page.keyboard.press('Control+k'); await page.getByRole('combobox').fill('landing'); await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByRole('heading',{level:1})).toBeFocused()
})
test('toast copy dedupe, hover/focus pause, dismiss focus; polling ends on departure', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read','clipboard-write'])
  let polls=0
  await page.route('**/api/wiki/jobs/toast-job',(route)=>{polls++;return route.fulfill({contentType:'application/json',body:JSON.stringify({status:'pending'})})})
  await page.goto('/wiki?jobId=toast-job'); await expect(page.getByRole('heading',{level:1})).toBeVisible()
  await page.locator('.ln').getByRole('link',{name:'Chat',exact:true}).press('Enter')
  await expect(page).toHaveURL(/chat$/)
  const count=polls; await page.waitForTimeout(2200); expect(polls).toBe(count)
  expect(await page.locator('.ui-toast').count()).toBe(0)
  for(let i=0;i<2;i++) { await page.keyboard.press('Control+k'); await page.getByRole('combobox').fill('copy'); await page.keyboard.press('Enter'); await expect(page.getByRole('combobox')).toHaveCount(0) }
  await expect(page.locator('.ui-toast')).toHaveCount(1)
  await page.locator('.ui-toast').hover(); await page.waitForTimeout(4200)
  await expect(page.locator('.ui-toast')).toHaveCount(1)
  const previous=page.getByRole('button',{name:'Open command palette'});await previous.focus()
  await page.getByRole('button',{name:'Dismiss notification'}).focus()
  await page.waitForTimeout(4200);await expect(page.locator('.ui-toast')).toHaveCount(1)
  await page.keyboard.press('Enter');await expect(previous).toBeFocused()
  await expect(page.locator('.ui-toast')).toHaveCount(0)
})
